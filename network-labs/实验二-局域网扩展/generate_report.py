# 六、思考题
doc.add_heading('六、思考题', level=1)
doc.add_paragraph('1. 为什么两台路由器之间需要配置静态路由？')
doc.add_paragraph('答：因为两台路由器各自只知道自己直连的网络，对于非直连的网络，路由器不知道应该将数据包转发到哪里。静态路由告诉路由器"要到达某个非直连网络，应该将数据包发给哪个下一跳地址"。如果不配置静态路由，路由器收到目的地址为非直连网络的数据包时，会因为找不到路由条目而丢弃数据包。')
doc.add_paragraph('')
doc.add_paragraph('2. 交换机和路由器在扩展局域网时各有什么优缺点？')
doc.add_paragraph('答：交换机扩展局域网的优点是配置简单、即插即用，缺点是不能隔离广播域，随着网络规模增大，广播流量会增加。路由器扩展局域网的优点是可以隔离广播域、支持不同网络互联，缺点是配置复杂、成本较高。')

