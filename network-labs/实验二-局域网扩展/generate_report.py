doc.add_paragraph('1. 局域网扩展的概念')
doc.add_paragraph('局域网（LAN）的扩展是指通过网络设备（如交换机、路由器）将多个局域网连接起来，实现更大范围的网络互联。扩展局域网的主要方式包括：使用集线器扩展（物理层）、使用交换机扩展（数据链路层）、使用路由器扩展（网络层）。')
doc.add_paragraph('')
doc.add_paragraph('2. 交换机扩展局域网')
doc.add_paragraph('交换机工作在数据链路层，可以连接多个局域网段。交换机通过MAC地址表进行数据帧的转发，可以有效减少冲突域，提高网络性能。但交换机不能隔离广播域，所有连接在同一交换机上的设备处于同一广播域中。')
doc.add_paragraph('')
doc.add_paragraph('3. 路由器扩展局域网')
doc.add_paragraph('路由器工作在网络层，可以连接不同的网络。路由器通过路由表决定数据包的转发路径，能够隔离广播域。当两个不同子网需要通信时，必须通过路由器进行转发。路由器需要配置静态路由或动态路由协议才能实现不同网络之间的数据转发。')
doc.add_paragraph('')
doc.add_paragraph('4. 静态路由')
doc.add_paragraph('静态路由是由网络管理员手动配置的路由条目。静态路由的配置命令格式为：')
doc.add_paragraph('ip route <目的网络> <子网掩码> <下一跳地址>')
doc.add_paragraph('静态路由适用于小型网络，配置简单，不占用网络带宽，但不能自动适应网络拓扑变化。')

